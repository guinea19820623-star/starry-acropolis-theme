// Turns d3-celestial's star and constellation-line data into hooks/stars.js:
// the stars down to magnitude 4.5, and the stick figures of the Greek-myth
// constellations this theme draws.
// Data: https://github.com/ofrohn/d3-celestial (BSD 3-Clause, (c) 2015 Olaf Frohn),
// files data/stars.6.json and data/constellations.lines.json.
// Run from the mod folder: node tools/gen-stars.mjs <folder holding those two files> hooks/stars.js
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const [dir, out] = process.argv.slice(2)
const stars = JSON.parse(readFileSync(join(dir, 'stars.6.json'), 'utf8'))
const lines = JSON.parse(readFileSync(join(dir, 'constellations.lines.json'), 'utf8'))

// Orion and his hunting dogs, the bull and the twins, the charioteer, Perseus
// and Andromeda with Pegasus and Cassiopeia, the bears, Orpheus' lyre, the swan,
// Zeus' eagle, the scorpion and the archer, the Nemean lion, the herdsman,
// the maiden and her scales, and the dolphin.
const PICKED = ['Ori', 'CMa', 'CMi', 'Tau', 'Gem', 'Aur', 'Per', 'And', 'Peg', 'Cas', 'UMa', 'UMi',
  'Lyr', 'Cyg', 'Aql', 'Sco', 'Sgr', 'Leo', 'Boo', 'Vir', 'Lib', 'Del']

const ra = lon => Math.round(((lon + 360) % 360) * 100) / 100
const deg = x => Math.round(x * 100) / 100

// [ra, dec, magnitude, colour index] for each star, brightest first
const list = stars.features
  .map(f => [ra(f.geometry.coordinates[0]), deg(f.geometry.coordinates[1]), Math.round(+f.properties.mag * 10) / 10, Math.round((+f.properties.bv || 0) * 100) / 100])
  .filter(s => s[2] <= 4.5)
  .sort((a, b) => a[2] - b[2])

const figures = {}
for (const id of PICKED) {
  const f = lines.features.find(x => x.id === id)
  if (!f) throw new Error(`no lines for ${id}`)
  figures[id] = f.geometry.coordinates.map(line => line.flatMap(([lon, lat]) => [ra(lon), deg(lat)]))
}

const js = `// Generated by tools/gen-stars.mjs from d3-celestial (BSD 3-Clause,
// (c) 2015 Olaf Frohn, https://github.com/ofrohn/d3-celestial).
// STARS: ra, dec (degrees, J2000), magnitude and B-V colour index, four
// numbers a star, brightest first. FIGURES: each constellation's lines as
// flat lists of ra, dec pairs.
export const STARS = ${JSON.stringify(list.flat())}
export const FIGURES = ${JSON.stringify(figures)}
`
writeFileSync(out, js)
console.log('stars', list.length, 'figures', PICKED.length, 'characters', js.length)
